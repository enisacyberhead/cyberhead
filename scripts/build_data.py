#!/usr/bin/env python3
"""Convert data/programmes.csv into data/programmes.js.

Run from the repository root:  python3 scripts/build_data.py

The output is a plain <script>-loadable file (window.PROGRAMMES = [...]),
so the site also works when index.html is opened straight from disk.
"""
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "programmes.csv"
DST = ROOT / "data" / "programmes.js"


def clean(value):
    return (value or "").replace("\r\n", "\n").replace("\r", "\n").strip()


def to_int(value):
    try:
        return int(clean(value))
    except ValueError:
        return 0


def main():
    with SRC.open(encoding="utf-8-sig", newline="") as fh:
        rows = list(csv.DictReader(fh))

    programmes, seen = [], set()
    for row in rows:
        institution = clean(row["Institution name"])
        name = clean(row["Programme name"])
        url = clean(row["Website URL"])

        # 32-character hex id, same shape as the original CYBERHEAD ids
        pid = hashlib.md5(f"{institution}|{name}|{url}".encode("utf-8")).hexdigest()
        n = 1
        while pid in seen:
            n += 1
            pid = hashlib.md5(f"{institution}|{name}|{url}|{n}".encode("utf-8")).hexdigest()
        seen.add(pid)

        programmes.append({
            "id": pid,
            "institution": institution,
            "name": name,
            "type": clean(row["Programme type"]),
            "url": url,
            "description": clean(row["Programme description"]),
            "cost": clean(row["Programme cost"]),
            "ects": {
                "total": to_int(row["ECTS - Total"]),
                "security": to_int(row["ECTS related to security computing/engineering disciplines"]),
                "law": to_int(row["ECTS related to law, ethics, policy, privacy, cybercrime disciplines"]),
                "org": to_int(row["ECTS related to Organizational, Risk management, business, compliance disciplines"]),
                "internship": to_int(row["ECTS compulsory internship"]),
                "other": to_int(row["ECTS - other"]),
            },
            "delivery": clean(row["Delivery method"]),
            "language": clean(row["Delivery language"]),
            "city": clean(row["City"]),
            "country": clean(row["Country"]),
            "established": clean(row["Established"]),
            "certification": clean(row["Professional certification"]),
            "specialists": clean(row["Specialists"]).lower() == "yes",
        })

    DST.write_text(
        "/* Generated by scripts/build_data.py from data/programmes.csv - do not edit by hand. */\n"
        "window.PROGRAMMES = " + json.dumps(programmes, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(programmes)} programmes to {DST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
